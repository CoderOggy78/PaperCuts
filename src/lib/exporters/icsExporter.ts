import type { DeadlineItem } from '../../types/schema'

/**
 * Escapes text according to RFC 5545 Section 3.3.11.
 * Characters needing escaping: backslash, semicolon, comma, newline.
 */
export function escapeICalText(str: string): string {
  return str
    .replace(/\\/g, '\\\\')
    .replace(/;/g, '\\;')
    .replace(/,/g, '\\,')
    .replace(/\r?\n/g, '\\n')
}

/**
 * Formats a Date object or YYYY-MM-DD string into RFC 5545 date formats.
 * For all-day events: VALUE=DATE:YYYYMMDD
 * For timed events: YYYYMMDDTHHMMSSZ
 */
export function formatICalDate(dateStr: string): string {
  // Expected YYYY-MM-DD
  const cleaned = dateStr.replace(/-/g, '')
  return cleaned
}

/**
 * Generates a standard RFC 5545 .ics file content for a single deadline or a collection.
 */
export function generateICSContent(
  deadlines: DeadlineItem[],
  documentTitle = 'PaperCuts Document Deadlines'
): string {
  const validDeadlines = deadlines.filter((d) => d.normalizedDate !== null)

  const now = new Date()
  const stamp = now
    .toISOString()
    .replace(/[-:]/g, '')
    .replace(/\.\d{3}/, '')

  const lines: string[] = [
    'BEGIN:VCALENDAR',
    'VERSION:2.0',
    'PRODID:-//PaperCuts//Document Intelligence//EN',
    'CALSCALE:GREGORIAN',
    'METHOD:PUBLISH',
    `X-WR-CALNAME:${escapeICalText(documentTitle)}`
  ]

  for (const item of validDeadlines) {
    const dateFormatted = formatICalDate(item.normalizedDate!)
    const uid = `papercut-${item.id}-${dateFormatted}@papercuts.local`
    const summary = escapeICalText(`[Deadline] ${item.eventName}`)

    let description = `Official Wording: "${item.originalDateText}"\\n`
    if (item.timeAndZone) {
      description += `Time/Zone: ${item.timeAndZone}\\n`
    }
    if (item.sourceCitation) {
      description += `Source Evidence (Page ${item.sourceCitation.pageNumber}): "${item.sourceCitation.excerpt}"\\n`
    }
    if (item.unresolvedAmbiguities) {
      description += `Note: ${item.unresolvedAmbiguities}\\n`
    }
    description += `Generated by PaperCuts Document Intelligence Workspace`

    lines.push('BEGIN:VEVENT')
    lines.push(`UID:${uid}`)
    lines.push(`DTSTAMP:${stamp}`)
    lines.push(`DTSTART;VALUE=DATE:${dateFormatted}`)
    lines.push(`DTEND;VALUE=DATE:${dateFormatted}`)
    lines.push(`SUMMARY:${summary}`)
    lines.push(`DESCRIPTION:${escapeICalText(description)}`)
    lines.push('STATUS:CONFIRMED')
    lines.push('TRANSP:TRANSPARENT')
    lines.push('END:VEVENT')
  }

  lines.push('END:VCALENDAR')
  return lines.join('\r\n')
}

/**
 * Triggers a browser download of the generated .ics file.
 */
export function downloadICS(content: string, filename = 'papercuts-deadlines.ics'): void {
  const blob = new Blob([content], { type: 'text/calendar;charset=utf-8' })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = filename
  document.body.appendChild(a)
  a.click()
  document.body.removeChild(a)
  URL.revokeObjectURL(url)
}
