import type { StructuredAnalysis, UserDocument } from '../../types/schema'

/**
 * Generates an executive Markdown Action Plan export.
 */
export function generateMarkdownExport(doc: UserDocument, analysis: StructuredAnalysis): string {
  const lines: string[] = []

  lines.push(`# Action Plan: ${doc.fileName}`)
  lines.push(`*Generated by PaperCuts Document Intelligence Workspace*`)
  lines.push(`\n> **NOTICE**: This document is an informational synthesis based on algorithmic text extraction and document intelligence. It does NOT constitute an official government determination, legal endorsement, or guaranteed award.\n`)

  lines.push(`## 1. Document Overview`)
  lines.push(`- **Document Title**: ${analysis.metadata.title}`)
  lines.push(`- **Document Type**: ${analysis.metadata.documentType}`)
  lines.push(`- **Issuing Entity**: ${analysis.metadata.issuingOrganization || 'Not explicitly stated'}`)
  lines.push(`- **Publication Date**: ${analysis.metadata.publicationDate || 'Not stated'}`)
  lines.push(`- **Audience**: ${analysis.metadata.relevantAudience || 'General applicants'}`)
  lines.push(`- **Analysis Engine**: ${analysis.providerDisplayName} (${analysis.providerMode})`)
  lines.push(`- **Analyzed At**: ${analysis.analysisTimestamp}`)
  lines.push(`- **Total Pages**: ${doc.pageCount}`)

  if (analysis.metadata.extractionWarnings && analysis.metadata.extractionWarnings.length > 0) {
    lines.push(`\n### Extraction Warnings`)
    analysis.metadata.extractionWarnings.forEach((w) => lines.push(`- ⚠️ ${w}`))
  }

  lines.push(`\n## 2. Priority Action Checklist`)
  if (analysis.actions.length === 0) {
    lines.push(`*No concrete actions identified.*`)
  } else {
    analysis.actions.forEach((act, idx) => {
      const checkbox = act.completed ? '[x]' : '[ ]'
      const dueStr = act.dueDate ? ` *(Due: ${act.dueDate})*` : ''
      lines.push(`### ${checkbox} Action ${idx + 1}: ${act.title}${dueStr}`)
      lines.push(`**Priority**: ${act.priority.toUpperCase()} — ${act.priorityRationale}`)
      lines.push(`\n${act.instructions}\n`)
      lines.push(`**Why it matters**: ${act.whyItMatters}`)
      if (act.prerequisites && act.prerequisites.length > 0) {
        lines.push(`**Prerequisites**: ${act.prerequisites.join(', ')}`)
      }
      if (act.sourceCitations && act.sourceCitations.length > 0) {
        lines.push(`\n**Source Evidence**:`)
        act.sourceCitations.forEach((cit) => {
          lines.push(`> "Page ${cit.pageNumber}: ${cit.excerpt}" [Verified in document: ${cit.verifiedInSource ? 'Yes' : 'No'}]`)
        })
      }
      lines.push('')
    })
  }

  lines.push(`\n## 3. Important Deadlines`)
  if (analysis.deadlines.length === 0) {
    lines.push(`*No specific deadlines extracted.*`)
  } else {
    analysis.deadlines.forEach((dl) => {
      lines.push(`- **${dl.eventName}**: \`${dl.originalDateText}\` (${dl.normalizedDate ? 'Standardized: ' + dl.normalizedDate : 'Unambiguous ISO date not available'})`)
      if (dl.timeAndZone) lines.push(`  - Time: ${dl.timeAndZone}`)
      if (dl.unresolvedAmbiguities) lines.push(`  - Note / Ambiguity: ${dl.unresolvedAmbiguities}`)
      if (dl.sourceCitation) {
        lines.push(`  - *Citation (Page ${dl.sourceCitation.pageNumber})*: "${dl.sourceCitation.excerpt}"`)
      }
    })
  }

  lines.push(`\n## 4. Required Supporting Documents`)
  if (analysis.requiredDocuments.length === 0) {
    lines.push(`*No specific documentation list stated.*`)
  } else {
    analysis.requiredDocuments.forEach((rd) => {
      const check = rd.completed ? '[x]' : '[ ]'
      lines.push(`- ${check} **${rd.title}** [${rd.status.toUpperCase()}]`)
      lines.push(`  - Rules: ${rd.submissionRules}`)
      if (rd.sourceCitation) {
        lines.push(`  - *Source (Page ${rd.sourceCitation.pageNumber})*: "${rd.sourceCitation.excerpt}"`)
      }
    })
  }

  lines.push(`\n## 5. Eligibility Criteria & Conditions`)
  analysis.eligibilityRequirements.forEach((req) => {
    lines.push(`### [${req.id}] ${req.category.toUpperCase()}: ${req.description}`)
    lines.push(`- **Status**: ${req.status.toUpperCase()}`)
    lines.push(`- **Exceptions/Conditions**: ${req.conditionsAndExceptions}`)
    if (req.profileEvaluationStatus) {
      lines.push(`- **Your Profile Assessment**: ${req.profileEvaluationStatus.toUpperCase().replace(/_/g, ' ')}`)
      if (req.profileEvaluationReason) lines.push(`  - ${req.profileEvaluationReason}`)
    }
    if (req.sourceCitations && req.sourceCitations.length > 0) {
      lines.push(`- **Evidence**:`)
      req.sourceCitations.forEach((cit) => {
        lines.push(`  > (Page ${cit.pageNumber}): "${cit.excerpt}"`)
      })
    }
    lines.push('')
  })

  lines.push(`\n## 6. Risks, Disqualifications & Ambiguities`)
  analysis.risksAndConditions.forEach((risk) => {
    lines.push(`- **${risk.title}** [${risk.type.toUpperCase()}]`)
    lines.push(`  ${risk.description}`)
  })

  if (analysis.questions && analysis.questions.length > 0) {
    lines.push(`\n## 7. Clarifications to Seek Before Submitting`)
    analysis.questions.forEach((q, idx) => {
      lines.push(`${idx + 1}. **${q.question}**`)
      lines.push(`   - *Why this matters*: ${q.whyItMatters}`)
    })
  }

  return lines.join('\n')
}

/**
 * Downloads arbitrary text as a file.
 */
export function downloadFile(content: string, filename: string, mimeType: string): void {
  const blob = new Blob([content], { type: mimeType })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = filename
  document.body.appendChild(a)
  a.click()
  document.body.removeChild(a)
  URL.revokeObjectURL(url)
}
